import test from 'node:test';
import assert from 'node:assert/strict';
test('avaliação corporal salva, compara e preserva treinos e atividades existentes',async()=>{
 const elements={},listeners={},handlers={};
 const el=id=>elements[id] ||= {innerHTML:'',textContent:'',hidden:false,value:'',dataset:{},addEventListener(type,fn){if(id==='#app-content')handlers[type]=fn},click(){}};
 const legacy={version:1,profile:{startDate:'2026-11-16'},sessions:[{id:'old',dayId:'A',date:'2026-11-16',week:1,sets:{},manual:true}],activities:[{id:'bike',type:'ciclismo',date:'2026-11-17',durationMin:30,distanceKm:10,intensity:'Leve',notes:''}],active:null};
 const store={'forca-em-casa-v1':JSON.stringify(legacy)};
 globalThis.document={querySelector:el,querySelectorAll:()=>[],createElement:()=>({click(){},remove(){}}),body:{append(){}}};
 globalThis.localStorage={getItem:key=>store[key]||null,setItem:(key,value)=>{store[key]=value}};
 globalThis.location={hash:'#dashboard',protocol:'file:'};
 globalThis.window={addEventListener:(key,fn)=>{listeners[key]=fn},scrollTo(){}};
 globalThis.confirm=()=>true;
 await import('../app.js');
 const click=(action,props={})=>handlers.click({target:{closest:()=>({dataset:{action,...props}})}});
 click('view-assessment');
 assert.match(el('#app-content').innerHTML,/Nova avaliação/);
 el('#body-date').value='2026-11-16';
 el('#body-weightKg').value='85,0';
 el('#body-heightCm').value='173';
 el('#body-waistCm').value='92';
 click('save-assessment');
 let state=JSON.parse(store['forca-em-casa-v1']);
 assert.equal(state.measurements.length,1);
 assert.equal(state.sessions.length,1);
 assert.equal(state.activities.length,1);
 assert.equal(state.measurements[0].weightKg,85);
 el('#body-date').value='2026-11-18';
 el('#body-weightKg').value='84,0';
 el('#body-waistCm').value='90';
 click('save-assessment');
 state=JSON.parse(store['forca-em-casa-v1']);
 assert.equal(state.measurements.length,2);
 assert.match(el('#app-content').innerHTML,/Evolução do peso/);
 assert.match(el('#app-content').innerHTML,/<svg/);
 assert.match(el('#app-content').innerHTML,/desde o primeiro registro/);
});
